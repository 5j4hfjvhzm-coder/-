    static func lookup(_ raw: String) -> (word: String, meaning: String)? {
        var w = raw.lowercased().replacingOccurrences(of: "’", with: "'")
        if w.hasSuffix("'s") { w.removeLast(2) }
        var candidates = [w]
        func strip(_ suffix: String, _ add: String = "") {
            if w.hasSuffix(suffix) && w.count > suffix.count + 1 {
                candidates.append(String(w.dropLast(suffix.count)) + add)
            }
        }
        strip("ies", "y"); strip("es"); strip("s")
        strip("ied", "y"); strip("ed"); strip("ed", "e")
        strip("ing"); strip("ing", "e")
        for c in candidates {
            if let m = words[c] { return (c, m) }
        }
        return nil
    }

